def read(path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def write(path, obj):
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2), encoding="utf-8")


def canonical(s):
    s = tuple(s)
    return min(s[i:] + s[:i] for i in range(4))


def measure(m):
    row = {k: m[k] for k in ("profile", "file", "width", "height", "semanticExact", "semanticBasis")}
    row["cells"] = m["width"]*m["height"]
    slots, materials = set(), set()
    uniform, transition, rotated = collections.Counter(), collections.Counter(), collections.Counter()
    for layer in ("land", "overlay"):
        packed, signatures = m[layer], m[layer + "Signatures"]
        t = u = unknown = active = 0
        layer_materials = set()
        for p, s in zip(packed, signatures):
            if p < 0:
                continue
            active += 1
            slot = p & 0x3fff
            slots.add(slot)
            if not s or min(s) <= 0:
                unknown += 1
                continue
            layer_materials.update(s)
            runtime = m["runtimeTypes"][slot] if slot < len(m["runtimeTypes"]) else -1
            if len(set(s)) == 1:
                u += 1
                uniform[(layer, s[0], runtime)] += 1
            else:
                t += 1
                transition[(layer, tuple(s), runtime)] += 1
                rotated[(layer, canonical(s), runtime)] += 1
        materials.update(layer_materials)
        row.update({layer + "Active": active, layer + "Transitions": t, layer + "Uniform": u,
                    layer + "Unknown": unknown, layer + "Materials": len(layer_materials)})
    homogeneous = sum(min(4, count) for count in uniform.values())
    row.update({"usedSlots": len(slots), "materials": len(materials), "uniformBudget": homogeneous,
                "transitionSignatures": len(transition), "canonicalSignatures": len(rotated),
                "uniqueCellBudget": sum(transition.values()) + homogeneous})
    for n in (4, 8, 16):
        row[f"n{n}"] = sum(min(n, c) for c in transition.values()) + homogeneous
        row[f"rotatedN{n}"] = sum(min(n, c) for c in rotated.values()) + homogeneous
    # Quantify the loss introduced by choosing one shared material per vertex.
    w, h = m["width"], m["height"]
    votes = collections.defaultdict(set)
    for i, s in enumerate(m["landSignatures"]):
        if not s:
            continue
        x, y = i % w, i // w
        for xy, value in zip(((x,y),(x+1,y),(x+1,y+1),(x,y+1)), s):
            votes[xy].add(value)
    row["conflictingVertices"] = sum(len(v) > 1 for v in votes.values())
    row["recoveredChangedCells"] = 0
    if m["fieldRecovered"]:
        field = np.asarray(m["field"]).reshape(h+1, w+1)
        for i, s in enumerate(m["landSignatures"]):
            x, y = i % w, i // w
            if s and s != [int(field[y,x]),int(field[y,x+1]),int(field[y+1,x+1]),int(field[y+1,x])]:
                row["recoveredChangedCells"] += 1
    return row


def summarize(rows):
    keys = ("width", "height", "cells", "landTransitions", "overlayTransitions", "usedSlots", "materials",
            "uniqueCellBudget", "n4", "n8", "n16", "rotatedN4", "rotatedN8", "rotatedN16")
    return {"count": len(rows), "max": {k:max(r[k] for r in rows) for k in keys},
            "median": {k:statistics.median(r[k] for r in rows) for k in keys},
            "overBudget": {k:{str(limit):sum(r[k] > limit for r in rows) for limit in (2048,4096)}
                           for k in ("uniqueCellBudget", "n4", "n8", "n16", "rotatedN4", "rotatedN8", "rotatedN16")}}


def statistics_run(root):
    inventory = read(root / "inventory.json")
    rows = []
    for item in inventory["maps"]:
        if "error" in item:
            raise RuntimeError(item)
        m = read(root/item["export"])
        row = measure(m)
        row["export"] = item["export"]
        rows.append(row)
    summaries = {"all":summarize(rows)}
    for name in ("base", "deja-vu"):
        summaries[name] = summarize([r for r in rows if r["profile"]==name])
    exact = [r for r in rows if r["semanticExact"]]
    if exact:
        summaries["exact"] = summarize(exact)
    write(root/"statistics.json", {"rows":rows,"summary":summaries})
    table = ["| Профиль / карта | Клетки | Переходы земля | Overlay активен / переходы | Слоты сейчас | Материалы земля / overlay / всего | A | B N=4 | N=8 | N=16 | Семантика |",
             "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    for r in rows:
        table.append(f"| {r['profile']}/{r['file']} | {r['width']}×{r['height']} | {r['landTransitions']} | {r['overlayActive']} / {r['overlayTransitions']} | {r['usedSlots']} | {r['landMaterials']} / {r['overlayMaterials']} / {r['materials']} | {r['uniqueCellBudget']} | {r['n4']} | {r['n8']} | {r['n16']} | {'точная' if r['semanticExact'] else 'гипотеза'} |")
    (root/"statistics-table.md").write_text("\n".join(table)+"\n",encoding="utf-8")
    print(json.dumps(summaries,ensure_ascii=False,indent=2))


def uniform_sources(atlas):
    sources = collections.defaultdict(list)
    for slot in atlas["catalog"]["slots"]:
        s = slot.get("corners", [])
        if not s:
            s = [slot.get("signature", {}).get(k, 0) for k in ("northWest","northEast","southEast","southWest")]
        if len(s)==4 and len(set(s))==1 and s[0]>0 and slot.get("assigned",False):
            sources[s[0]].append(slot["slot"])
    return sources


def choose_crop(root):
    inventory = read(root/"inventory.json")
    atlases = {a["directory"]:a for a in inventory["atlases"]}
    candidates = []
    for item in inventory["maps"]:
        if not item.get("semanticExact") or not item.get("fieldRecovered"):
            continue
        m = read(root/item["export"]); w,h=m["width"],m["height"]
        field=np.asarray(m["field"],dtype=np.int32).reshape(h+1,w+1)
        sources=uniform_sources(atlases[m["atlasDirectory"]])
        sigs=m["landSignatures"]
        tr=np.asarray([bool(s) and len(set(s))>1 for s in sigs]).reshape(h,w)
        overlay=np.asarray(m["overlay"]).reshape(h,w)
        for y in range(0,h-31,8):
            for x in range(0,w-31,8):
                materials=set(int(v) for v in np.unique(field[y:y+33,x:x+33]))
                if len(materials)<3 or len(materials)>8 or not materials <= sources.keys():
                    continue
                if (overlay[y:y+32,x:x+32]>=0).any():
                    continue
                transitions=int(tr[y:y+32,x:x+32].sum())
                if transitions<200:
                    continue
                conflicts=0
                for yy in range(y,y+32):
                    for xx in range(x,x+32):
                        s=sigs[yy*w+xx]
                        fs=[int(field[yy,xx]),int(field[yy,xx+1]),int(field[yy+1,xx+1]),int(field[yy+1,xx])]
                        conflicts += s != fs
                # Prefer exact recovery; then abundant transitions, then few materials.
                candidates.append((conflicts,-transitions,len(materials),item["export"],x,y,sorted(materials)))
    if not candidates:
        raise RuntimeError("No suitable exact crop with uniform sources")
    candidates.sort()
    best=candidates[0]
    crop={"export":best[3],"x":best[4],"y":best[5],"size":32,"materials":best[6],
          "recoveredChangedCells":best[0],"transitions":-best[1],"candidateCount":len(candidates)}
    write(root/"crop.json",crop)
    print(json.dumps(crop,indent=2))
    return crop


def hash_noise(x,y,seed):
    # Lattice value noise; global coordinates/seed give equal values on cell edges.
    def lattice(a,b):
        z=(a.astype(np.uint64)*np.uint64(0x9e3779b1) ^ b.astype(np.uint64)*np.uint64(0x85ebca77) ^ np.uint64(seed))
        z=(z^(z>>np.uint64(16)))*np.uint64(0x7feb352d)
        z=(z^(z>>np.uint64(15)))*np.uint64(0x846ca68b)
        z=z^(z>>np.uint64(16))
        return ((z & np.uint64(0xffffff)).astype(np.float32)/float(0xffffff))*2-1
    ix=np.floor(x).astype(np.int64);iy=np.floor(y).astype(np.int64)
    fx=x-ix;fy=y-iy;fx=fx*fx*(3-2*fx);fy=fy*fy*(3-2*fy)
    return ((1-fx)*lattice(ix,iy)+fx*lattice(ix+1,iy))*(1-fy)+((1-fx)*lattice(ix,iy+1)+fx*lattice(ix+1,iy+1))*fy


def weights(field, wx, wy, materials):
    # Shared bilinear weights plus per-material world noise. Multiplication
    # by w*(1-w) preserves pure corners/cells and shared uniform edges exactly.
    xx=np.clip(wx,0,field.shape[1]-1.000001)
    yy=np.clip(wy,0,field.shape[0]-1.000001)
    ix=np.floor(xx).astype(int);iy=np.floor(yy).astype(int);fx=xx-ix;fy=yy-iy
    fs=(field[iy,ix],field[iy,ix+1],field[iy+1,ix+1],field[iy+1,ix])
    bs=((1-fx)*(1-fy),fx*(1-fy),fx*fy,(1-fx)*fy)
    raw=np.stack([sum(b*(v==m) for v,b in zip(fs,bs)) for m in materials],axis=-1)
    for i,material in enumerate(materials):
        noise=.28*hash_noise(wx*1.7,wy*1.7,material&0xffff)+.07*hash_noise(wx*6.3,wy*6.3,(material&0xffff)+101)
        raw[...,i]+=noise*4*raw[...,i]*(1-raw[...,i])
    # Blend only within .12 of the winning score; wide bilinear haze is avoided.
    edge=np.clip((raw-raw.max(axis=-1,keepdims=True)+.12)/.12,0,1)
    edge=edge*edge*(3-2*edge)
    return edge/np.maximum(edge.sum(axis=-1,keepdims=True),1e-9)


def render(root,crop,pixels=128):
    m=read(root/crop["export"]); w,h=m["width"],m["height"]
    inventory=read(root/"inventory.json")
    atlas=next(a for a in inventory["atlases"] if a["directory"]==m["atlasDirectory"])
    sources=uniform_sources(atlas);materials=crop["materials"]
    field=np.asarray(m["field"],dtype=np.int32).reshape(h+1,w+1)
    x0,y0,size=crop["x"],crop["y"],crop["size"]
    before=Image.new("RGB",(size*pixels,size*pixels))
    cache={};manifest=[];textures={}
    for material in materials:
        slot=min(sources[material]); im=Image.open(root/atlas["directory"]/f"{slot}.png").convert("RGB")
        margin=im.width//16
        textures[material]=np.asarray(im.crop((margin,margin,im.width-margin,im.height-margin)),dtype=np.float32)
        name=next(f["name"] for f in atlas["catalog"]["families"] if f["id"]==material)
        manifest.append({"material":material,"name":name,"slot":slot,"sourcePixels":im.width,"uniformVariantsAvailable":len(sources[material])})
    for y in range(size):
        for x in range(size):
            packed=m["land"][(y+y0)*w+x+x0]; slot=packed&0x3fff;rot=packed>>14
            if slot not in cache:
                cache[slot]=Image.open(root/atlas["directory"]/f"{slot}.png").convert("RGB")
            # Grid Y grows opposite to conventional image preview Y.
            # Decode uses inverse packed rotation in grid space, then reflect once.
            tile=cache[slot].transpose(Image.Transpose.FLIP_TOP_BOTTOM).rotate(rot*90,expand=False)
            margin=tile.width//16
            tile=tile.crop((margin,margin,tile.width-margin,tile.height-margin))
            tile=tile.resize((pixels,pixels),Image.Resampling.LANCZOS)
            before.paste(tile,(x*pixels,y*pixels))
    after=Image.new("RGB",before.size)
    macro=Image.new("RGB",before.size)
    for y in range(size):
        wx,wy=np.meshgrid(x0+(np.arange(size*pixels)+.5)/pixels,y0+y+(np.arange(pixels)+.5)/pixels)
        blend=weights(field,wx,wy,materials)
        rgb=np.zeros((*wx.shape,3),dtype=np.float32)
        for i,material in enumerate(materials):
            tex=textures[material];ts=tex.shape[0]
            # Period exactly one cell; expose repetition instead of hiding it.
            tx=np.floor(wx*ts).astype(int)%ts;ty=np.floor(wy*ts).astype(int)%ts
            sampled=tex[(ts-1-ty),tx]
            rgb+=sampled*blend[...,i,None]
        after.paste(Image.fromarray(np.clip(np.rint(rgb),0,255).astype(np.uint8)),(0,y*pixels))
        variation=1+.13*hash_noise(wx/7,wy/7,101)+.05*hash_noise(wx/2.3,wy/2.3,103)
        macro.paste(Image.fromarray(np.clip(np.rint(rgb*variation[...,None]),0,255).astype(np.uint8)),(0,y*pixels))
    images={"current":before,"baked":after,"baked-macro":macro}
    # Pixel deduplication is typed. Report both pure pixel and type-aware counts.
    counts={}
    for label,im in images.items():
        hashes=set();typed=set();transition_hashes=set();uniform_hashes=set()
        for y in range(size):
            for x in range(size):
                tile=im.crop((x*pixels,y*pixels,(x+1)*pixels,(y+1)*pixels))
                digest=hashlib.sha256(tile.tobytes()).hexdigest();hashes.add(digest)
                p=m["land"][(y+y0)*w+x+x0];slot=p&0x3fff;runtime=m["runtimeTypes"][slot]
                typed.add((digest,runtime))
                s=m["landSignatures"][(y+y0)*w+x+x0]
                (transition_hashes if len(set(s))>1 else uniform_hashes).add(digest)
        counts[label]={"pixelUnique":len(hashes),"typedUnique":len(typed),"transitionPixelUnique":len(transition_hashes),"uniformPixelUnique":len(uniform_hashes),"pages":math.ceil(len(typed)/64)}
        im.transpose(Image.Transpose.FLIP_TOP_BOTTOM).save(root/f"{label}.png")
    # Side by side at the same pixel scale; also supply a small navigation preview.
    pair=Image.new("RGB",(before.width*2,before.height+48),(25,25,25));draw=ImageDraw.Draw(pair)
    draw.text((12,12),"CURRENT: decoded SEC slots + rotations (unlit ground)",fill="white")
    draw.text((before.width+12,12),"BAKED: shared material field + continuous world noise",fill="white")
    pair.paste(before.transpose(Image.Transpose.FLIP_TOP_BOTTOM),(0,48));pair.paste(after.transpose(Image.Transpose.FLIP_TOP_BOTTOM),(before.width,48))
    pair.save(root/"current-after.png")
    pair.resize((2048,1036),Image.Resampling.LANCZOS).save(root/"current-after-preview.png")
    # Same boundary point evaluated through adjacent cells; no tile-local seed.
    xx,yy=np.meshgrid(np.arange(x0+1,x0+size),np.linspace(y0+.01,y0+size-.01,801))
    a=weights(field,xx-1e-6,yy,materials);b=weights(field,xx+1e-6,yy,materials)
    continuity=float(np.max(np.abs(a-b)))
    result={"crop":crop,"map":m["path"],"sha256":m["sha256"],"atlasPixelSha256":atlas["pixelSha256"],
            "semanticBasis":m["semanticBasis"],"fieldBasis":m["fieldBasis"],"pixelsPerCell":pixels,
            "materials":manifest,"counts":counts,"maxWeightJumpAtBoundaryEpsilon1e6":continuity,
            "parameters":{"weightNoiseAmplitudes":[.28,.07],"noiseFrequencyPerCell":[1.7,6.3],"blendScoreWidth":.12,"texturePeriodCells":1,"sourceUvInsetFraction":1/16,"macroAmplitudes":[.13,.05],"macroPeriodCells":[7,2.3]}}
    write(root/"prototype-result.json",result)
    print(json.dumps(result,ensure_ascii=False,indent=2))


def main():
    parser=argparse.ArgumentParser();parser.add_argument("root",type=Path);parser.add_argument("action",choices=("stats","render"));args=parser.parse_args()
    root=args.root.resolve()
    if root.name!="build-tests-terrain-bake-research-0":
        raise SystemExit("Outputs must stay in the private ignored research directory")
    if args.action=="stats":statistics_run(root)
    else:render(root,choose_crop(root))


if __name__=="__main__":
    main()
